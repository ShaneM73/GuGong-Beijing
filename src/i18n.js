const IDX = { en: 0, ja: 1, ko: 2 };
const TERM = { en: {}, ja: {}, ko: {} };
for (const [zh, en, ja, ko] of TERMS) { TERM.en[zh] = en; TERM.ja[zh] = ja; TERM.ko[zh] = ko; }
const SEP = { en: ' · ', ja: '・', ko: ' · ' };

/** Translate a name or "A · B" category label. */
export function term(zh, lang) {
  if (!zh || lang === 'zh') return zh;
  const t = TERM[lang];
  if (t[zh]) return t[zh];
  return zh.includes(' · ') ? zh.split(' · ').map(p => t[p] ?? p).join(SEP[lang]) : zh;
}
export function info(s, lang) {
  if (lang === 'zh') return s.info || '';
  const r = INFO[s.name + '|' + s.kind] || INFO[s.name]; return r ? r[IDX[lang]] : (s.info || '');
}
export function dims(s, lang) {
  if (lang === 'zh') return s.dims || '';
  const r = DIMS[s.name]; return r ? r[IDX[lang]] : (s.dims || '');
}
/** Coverage check used at build time: returns the strings with no translation. */
export function missing(sites) {
  const out = [];
  for (const lang of ['en', 'ja', 'ko']) for (const s of sites) {
    if (!TERM[lang][s.name]) out.push(`${lang} name ${s.name}`);
    for (const p of (s.kind || '').split(' · ')) if (p && !TERM[lang][p]) out.push(`${lang} kind ${p}`);
    if (s.dims && !DIMS[s.name]) out.push(`${lang} dims ${s.name}`);
    if (s.info && !(INFO[s.name + '|' + s.kind] || INFO[s.name])) out.push(`${lang} info ${s.name}`);
  }
  return [...new Set(out)];
}
